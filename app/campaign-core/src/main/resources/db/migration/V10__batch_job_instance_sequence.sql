-- Spring Batch 6 uses BATCH_JOB_INSTANCE_SEQ (V4 created the legacy BATCH_JOB_SEQ).
-- Run migrations with batch launches paused. Never reset IDs below existing history.
CREATE TABLE IF NOT EXISTS BATCH_JOB_INSTANCE_SEQ (
    ID BIGINT NOT NULL,
    UNIQUE_KEY CHAR(1) NOT NULL,
    CONSTRAINT UNIQUE_KEY_UN UNIQUE (UNIQUE_KEY)
);
INSERT INTO BATCH_JOB_INSTANCE_SEQ (ID, UNIQUE_KEY)
SELECT GREATEST(COALESCE((SELECT MAX(JOB_INSTANCE_ID) FROM BATCH_JOB_INSTANCE), 0),
                COALESCE((SELECT MAX(ID) FROM BATCH_JOB_SEQ), 0)), '0'
ON DUPLICATE KEY UPDATE ID = GREATEST(ID, VALUES(ID));
